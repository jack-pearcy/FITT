package com.fitt.workouts.service;

import com.fitt.workouts.dto.AddExerciseEntryRequest;
import com.fitt.workouts.dto.CreateWorkoutSessionRequest;
import com.fitt.workouts.dto.LogSetRequest;
import com.fitt.workouts.dto.WorkoutSessionResponse;
import com.fitt.workouts.persistence.entity.ExerciseEntity;
import com.fitt.workouts.persistence.entity.ExerciseEntryEntity;
import com.fitt.workouts.persistence.entity.SetEntryEntity;
import com.fitt.workouts.persistence.entity.WorkoutSessionEntity;
import com.fitt.workouts.repository.ExerciseRepository;
import com.fitt.workouts.repository.WorkoutSessionRepository;
import com.fitt.workouts.service.exception.ExerciseNotFoundException;
import com.fitt.workouts.service.exception.WorkoutSessionNotFoundException;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.util.ReflectionTestUtils;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

// Service unit test for WorkoutSessionServiceImpl. Covers all 10 public
// methods plus the two loadAndVerify failure branches (404 not found,
// 403 owned by someone else). The service constructs hierarchical
// entity graphs (session has entries, entries have sets) so several
// tests use ArgumentCaptor to walk the saved object structure, and
// several use ReflectionTestUtils to assign IDs that would normally be
// generated by the database. No Spring context, no embedded database,
// pure JUnit plus Mockito plus AssertJ.
@ExtendWith(MockitoExtension.class)
class WorkoutSessionServiceImplTest {

    private static final Long OWNER_USER_ID = 42L;
    private static final Long OTHER_USER_ID = 99L;
    private static final Long SESSION_ID = 100L;
    private static final Long EXERCISE_ID = 5L;
    private static final Long ENTRY_ID = 300L;
    private static final Long SET_ID = 400L;
    private static final Long PLAN_ID = 7L;

    @Mock
    private WorkoutSessionRepository sessionRepository;

    @Mock
    private ExerciseRepository exerciseRepository;

    @InjectMocks
    private WorkoutSessionServiceImpl service;

    @Test
    void createSession_validRequest_setsAllFieldsIncludingPlanIdAndNotes() {
        Instant startedAt = Instant.parse("2026-05-26T18:00:00Z");
        CreateWorkoutSessionRequest request = new CreateWorkoutSessionRequest(startedAt, PLAN_ID, "leg day");

        // Capture the saved entity to verify all four fields were wired
        // correctly. ownerUserId and startedAt come from constructor args,
        // planId and notes are setter calls that the service makes after.
        ArgumentCaptor<WorkoutSessionEntity> captor = ArgumentCaptor.forClass(WorkoutSessionEntity.class);
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        WorkoutSessionResponse response = service.createSession(OWNER_USER_ID, request);

        verify(sessionRepository).save(captor.capture());
        WorkoutSessionEntity saved = captor.getValue();
        assertThat(saved.getOwnerUserId()).isEqualTo(OWNER_USER_ID);
        assertThat(saved.getStartedAt()).isEqualTo(startedAt);
        assertThat(saved.getPlanId()).isEqualTo(PLAN_ID);
        assertThat(saved.getNotes()).isEqualTo("leg day");
        // New session has no entries yet. toResponse maps an empty list.
        assertThat(response.exerciseEntries()).isEmpty();
    }

    @Test
    void listSessions_returnsAllSessionsForOwnerInRepositoryOrder() {
        // Repository orders newest first via the derived finder name.
        // Service is a pure pass-through with mapping, no resorting.
        WorkoutSessionEntity newer = sessionWithId(SESSION_ID);
        WorkoutSessionEntity older = sessionWithId(SESSION_ID + 1);
        when(sessionRepository.findByOwnerUserIdOrderByStartedAtDesc(OWNER_USER_ID))
                .thenReturn(List.of(newer, older));

        List<WorkoutSessionResponse> responses = service.listSessions(OWNER_USER_ID);

        assertThat(responses).hasSize(2);
        assertThat(responses.get(0).id()).isEqualTo(SESSION_ID);
        assertThat(responses.get(1).id()).isEqualTo(SESSION_ID + 1);
    }

    @Test
    void countCompletedSessions_delegatesToRepositoryWithFinishedAtFilter() {
        when(sessionRepository.countByOwnerUserIdAndPlanIdAndFinishedAtIsNotNull(OWNER_USER_ID, PLAN_ID))
                .thenReturn(7L);

        long count = service.countCompletedSessions(OWNER_USER_ID, PLAN_ID);

        assertThat(count).isEqualTo(7L);
    }

    @Test
    void getSession_notFound_throwsWorkoutSessionNotFoundException() {
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.getSession(OWNER_USER_ID, SESSION_ID))
                .isInstanceOf(WorkoutSessionNotFoundException.class);
    }

    @Test
    void getSession_notOwnedByCaller_throwsAccessDeniedException() {
        // Session exists but belongs to OTHER_USER_ID. loadAndVerify must
        // throw before returning the session to any further service logic.
        WorkoutSessionEntity foreignSession = sessionFor(OTHER_USER_ID);
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(foreignSession));

        assertThatThrownBy(() -> service.getSession(OWNER_USER_ID, SESSION_ID))
                .isInstanceOf(AccessDeniedException.class);
    }

    @Test
    void finishSession_setsFinishedAtTimestampAndSaves() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        service.finishSession(OWNER_USER_ID, SESSION_ID);

        // finishedAt was null before, now it must be set. We do not pin to
        // an exact value because Instant.now() is non-deterministic.
        assertThat(session.getFinishedAt()).isNotNull();
        verify(sessionRepository).save(session);
    }

    @Test
    void deleteSession_ownedByCaller_callsRepositoryDelete() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));

        service.deleteSession(OWNER_USER_ID, SESSION_ID);

        verify(sessionRepository).delete(session);
    }

    @Test
    void addExerciseEntry_appendsAtNextOrderIndexAndSyncsBothSides() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        // Pre-existing entry at orderIndex 0 so the new entry must land at 1.
        ExerciseEntity existingExercise = exerciseWithId(EXERCISE_ID + 1);
        session.addExerciseEntry(new ExerciseEntryEntity(existingExercise, 0));

        ExerciseEntity newExercise = exerciseWithId(EXERCISE_ID);
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(exerciseRepository.findById(EXERCISE_ID)).thenReturn(Optional.of(newExercise));
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        service.addExerciseEntry(OWNER_USER_ID, SESSION_ID, new AddExerciseEntryRequest(EXERCISE_ID));

        assertThat(session.getExerciseEntries()).hasSize(2);
        ExerciseEntryEntity appended = session.getExerciseEntries().get(1);
        assertThat(appended.getOrderIndex()).isEqualTo(1);
        assertThat(appended.getExercise()).isEqualTo(newExercise);
        // session.addExerciseEntry sets the workoutSession back-reference.
        assertThat(appended.getWorkoutSession()).isEqualTo(session);
    }

    @Test
    void addExerciseEntry_exerciseNotInLibrary_throwsExerciseNotFoundException() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(exerciseRepository.findById(EXERCISE_ID)).thenReturn(Optional.empty());

        assertThatThrownBy(() ->
                service.addExerciseEntry(OWNER_USER_ID, SESSION_ID, new AddExerciseEntryRequest(EXERCISE_ID)))
                .isInstanceOf(ExerciseNotFoundException.class);

        // The exception path must not save anything.
        verify(sessionRepository, never()).save(any(WorkoutSessionEntity.class));
    }

    @Test
    void removeExerciseEntry_byIdInSession_removesFromEntriesList() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        ExerciseEntity exercise = exerciseWithId(EXERCISE_ID);
        ExerciseEntryEntity entry = new ExerciseEntryEntity(exercise, 0);
        // DB-generated id needs ReflectionTestUtils because no DB runs here.
        ReflectionTestUtils.setField(entry, "id", ENTRY_ID);
        session.addExerciseEntry(entry);

        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        service.removeExerciseEntry(OWNER_USER_ID, SESSION_ID, ENTRY_ID);

        assertThat(session.getExerciseEntries()).isEmpty();
    }

    @Test
    void logSet_appendsSetAtNextSetNumberAndMarksCompletedTrue() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        ExerciseEntity exercise = exerciseWithId(EXERCISE_ID);
        ExerciseEntryEntity entry = new ExerciseEntryEntity(exercise, 0);
        ReflectionTestUtils.setField(entry, "id", ENTRY_ID);
        // Pre-existing set at setNumber 1 so the new set must land at 2.
        entry.addSetEntry(new SetEntryEntity(1, new BigDecimal("100"), 10, null));
        session.addExerciseEntry(entry);

        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        LogSetRequest request = new LogSetRequest(8, new BigDecimal("105"), new BigDecimal("8.5"));
        service.logSet(OWNER_USER_ID, SESSION_ID, ENTRY_ID, request);

        assertThat(entry.getSetEntries()).hasSize(2);
        SetEntryEntity newSet = entry.getSetEntries().get(1);
        assertThat(newSet.getSetNumber()).isEqualTo(2);
        assertThat(newSet.getReps()).isEqualTo(8);
        // BigDecimal compareTo ignores scale; equals does not.
        assertThat(newSet.getWeight()).isEqualByComparingTo(new BigDecimal("105"));
        assertThat(newSet.getRpe()).isEqualByComparingTo(new BigDecimal("8.5"));
        // Service marks the set completed immediately after creating it.
        assertThat(newSet.isCompleted()).isTrue();
    }

    @Test
    void deleteSet_byIdInEntry_removesSetViaEntrySync() {
        WorkoutSessionEntity session = sessionFor(OWNER_USER_ID);
        ExerciseEntity exercise = exerciseWithId(EXERCISE_ID);
        ExerciseEntryEntity entry = new ExerciseEntryEntity(exercise, 0);
        ReflectionTestUtils.setField(entry, "id", ENTRY_ID);
        SetEntryEntity set = new SetEntryEntity(1, new BigDecimal("100"), 10, null);
        ReflectionTestUtils.setField(set, "id", SET_ID);
        entry.addSetEntry(set);
        session.addExerciseEntry(entry);

        when(sessionRepository.findById(SESSION_ID)).thenReturn(Optional.of(session));
        when(sessionRepository.save(any(WorkoutSessionEntity.class)))
                .thenAnswer(invocation -> invocation.getArgument(0));

        service.deleteSet(OWNER_USER_ID, SESSION_ID, ENTRY_ID, SET_ID);

        assertThat(entry.getSetEntries()).isEmpty();
    }

    // Test helpers

    private WorkoutSessionEntity sessionWithId(Long id) {
        WorkoutSessionEntity session = new WorkoutSessionEntity(OWNER_USER_ID, Instant.parse("2026-05-26T18:00:00Z"));
        ReflectionTestUtils.setField(session, "id", id);
        return session;
    }

    private WorkoutSessionEntity sessionFor(Long ownerUserId) {
        WorkoutSessionEntity session = new WorkoutSessionEntity(ownerUserId, Instant.parse("2026-05-26T18:00:00Z"));
        ReflectionTestUtils.setField(session, "id", SESSION_ID);
        return session;
    }

    private ExerciseEntity exerciseWithId(Long id) {
        ExerciseEntity exercise = new ExerciseEntity(null, "Bench Press", "CHEST", false);
        ReflectionTestUtils.setField(exercise, "id", id);
        return exercise;
    }
}